#!/usr/bin/env python3
import sys
import os
import re
from datetime import datetime

# Pola regex sederhana untuk nangkep output Nuclei (contoh paling umum)
NUCLEI_PATTERN = re.compile(r'\[(.*?)\]\s+\[(.*?)\]\s+\[(.*?)\]\s+(.*)')

def parse_log(filepath):
    if not os.path.exists(filepath):
        print(f"[-] File tidak ditemukan: {filepath}")
        sys.exit(1)
    
    findings = []
    with open(filepath, 'r', encoding='utf-8', errors='ignore') as f:
        for line in f:
            # Coba parsing format Nuclei: [template] [protocol] [severity] url
            match = NUCLEI_PATTERN.search(line)
            if match:
                template, protocol, severity, url = match.groups()
                findings.append({
                    "template": template,
                    "protocol": protocol,
                    "severity": severity.upper(),
                    "url": url.strip()
                })
    
    return findings

def generate_report(filepath, findings):
    target_name = os.path.basename(filepath).replace('.log', '')
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    report_file = filepath.replace('.log', '_report.md')
    
    with open(report_file, 'w', encoding='utf-8') as f:
        f.write(f"# 🚨 Auto-Generated Vulnerability Report\n\n")
        f.write(f"**Date:** {timestamp}\n")
        f.write(f"**Source Log:** `{os.path.basename(filepath)}`\n")
        f.write(f"**Total Findings:** {len(findings)}\n\n")
        f.write("---\n\n")
        
        if not findings:
            f.write("Tidak ada kerentanan yang terdeteksi dari format log yang dikenali.\n")
        else:
            f.write("## Findings\n\n")
            f.write("| Severity | Template | URL |\n")
            f.write("| :--- | :--- | :--- |\n")
            for item in findings:
                f.write(f"| **{item['severity']}** | `{item['template']}` | {item['url']} |\n")
            
            f.write("\n\n---\n*Generated by TRX Arsenal (Auto-Convert)*\n")
    
    print(f"[+] Laporan berhasil dibuat: {report_file}")
    print(f"[*] Total temuan: {len(findings)}")

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python3 log_to_report.py <path_ke_file_log>")
        sys.exit(1)
    
    log_path = sys.argv[1]
    findings = parse_log(log_path)
    generate_report(log_path, findings)
